const cache = new Map();

export const CHAR_W = 4;
export const CHAR_H = 5;

export function textWidth(s) {
  return Math.max(0, String(s).length * CHAR_W - 1);
}

/** Render text to a cached 1x canvas. */
export function textCanvas(text, color = '#fff') {
  const s = String(text).toUpperCase();
  const key = `${color}|${s}`;
  let c = cache.get(key);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = Math.max(1, textWidth(s));
  c.height = CHAR_H;
  const g = c.getContext('2d');
  g.fillStyle = color;
  [...s].forEach((ch, i) => {
    const glyph = G[ch] || G['?'];
    for (let y = 0; y < 5; y++) for (let x = 0; x < 3; x++) if (glyph[y * 3 + x] === '#') g.fillRect(i * CHAR_W + x, y, 1, 1);
  });
  if (cache.size > 800) cache.clear();
  cache.set(key, c);
  return c;
}

export function drawText(ctx, text, x, y, color = '#fff', align = 'left') {
  const c = textCanvas(text, color);
  const dx = align === 'center' ? Math.round(x - c.width / 2) : align === 'right' ? x - c.width : x;
  ctx.drawImage(c, dx, Math.round(y));
  return c.width;
}
